/**
 * Adapter unit tests: deterministic patch, silent Bedrock failure, Virtual_Copy safety.
 * Uses the real engine; only the Bedrock call is replaced.
 * Validates: Requirements 4.7, 6.1, 6.2, 6.3, 6.5, 7.9
 */
import { afterEach, describe, expect, it, vi } from "vitest";
import type { SpliceRange } from "../../../../packages/morpheus-ast-core/src/contracts.js";
import { createInfraShieldAdapter, type InfraShieldAdapter, type CyberCityLayout, type FaultType } from "../adapter";

// --- Helpers ---

async function loadAdapter(): Promise<{
  adapter: InfraShieldAdapter;
  layout: CyberCityLayout;
  bedrock: { readonly mock: { readonly calls: readonly unknown[] } };
}> {
  const adapter = createInfraShieldAdapter();
  const bedrock = vi.spyOn(adapter["engine"], "generateBedrockPatch").mockRejectedValue(new Error("no credentials"));
  const layout = await adapter.loadSampleRepository();
  return { adapter, layout, bedrock };
}

async function flushPromises(): Promise<void> {
  await new Promise<void>((resolve) => setTimeout(resolve, 0));
}

/** Finds a function for which an UNCAUGHT_EXCEPTION fault yields a deterministic patch. */
async function injectPatchable(adapter: InfraShieldAdapter, layout: CyberCityLayout): Promise<string> {
  for (const node of layout.nodes) {
    await adapter.injectFault({ targetFunctionId: node.id, faultType: "UNCAUGHT_EXCEPTION" });
    if (adapter.getSREDashboard().lastPatch !== null) return node.id;
  }
  throw new Error("no function in the sample yields a deterministic patch");
}

/** Reads the Virtual_Copy text of a file through the adapter's read-only accessor. */
function readVirtual(adapter: InfraShieldAdapter, filePath: string): string {
  const text = adapter.getSourceText(filePath);
  if (text === undefined) throw new Error(`file not loaded: ${filePath}`);
  return text;
}

afterEach(() => {
  vi.restoreAllMocks();
});

describe("deterministic patch", () => {
  it("is labelled deterministic with an honest rationale for UNCAUGHT_EXCEPTION", async () => {
    const { adapter, layout } = await loadAdapter();
    await injectPatchable(adapter, layout);

    const patch = adapter.getSREDashboard().lastPatch;
    expect(patch).not.toBeNull();
    expect(patch?.modelId).toBe("deterministic");
    expect(patch?.rationale).toMatch(/rule-based/i);
    expect(patch?.rationale).toMatch(/not generated by an AI model/i);
    expect(patch?.suggestedSplices.length).toBeGreaterThan(0);
  });

  it("is null for a fault type with no remediation category", async () => {
    const { adapter, layout } = await loadAdapter();
    const faultType: FaultType = "LATENCY";
    const target = layout.nodes[0];
    if (target === undefined) throw new Error("sample has no functions");

    await adapter.injectFault({ targetFunctionId: target.id, faultType });
    await flushPromises();

    expect(adapter.getSREDashboard().lastPatch).toBeNull();
  });
});

describe("Bedrock failure", () => {
  it("keeps the deterministic patch and writes nothing to the console", async () => {
    const { adapter, layout, bedrock } = await loadAdapter();
    const error = vi.spyOn(console, "error").mockImplementation(() => undefined);
    const warn = vi.spyOn(console, "warn").mockImplementation(() => undefined);
    const log = vi.spyOn(console, "log").mockImplementation(() => undefined);

    await injectPatchable(adapter, layout);
    await flushPromises();

    expect(bedrock.mock.calls.length).toBeGreaterThan(0);
    expect(adapter.getSREDashboard().lastPatch?.modelId).toBe("deterministic");
    expect(error).not.toHaveBeenCalled();
    expect(warn).not.toHaveBeenCalled();
    expect(log).not.toHaveBeenCalled();
  });
});

describe("Virtual_Copy", () => {
  it("is unchanged when applyMutation rejects", async () => {
    const { adapter, layout } = await loadAdapter();
    const filePath = layout.nodes[0]?.filePath;
    if (filePath === undefined) throw new Error("sample has no functions");
    const before = readVirtual(adapter, filePath);

    await expect(adapter.applyMutation({ splices: [] })).rejects.toThrow();
    await expect(
      adapter.applyMutation({
        splices: [{ filePath: "no/such/file.ts", startIndex: 0, endIndex: 0, replacement: "x", description: "bad" }],
      })
    ).rejects.toThrow();

    expect(readVirtual(adapter, filePath)).toBe(before);
  });

  it("is restored by reset() after an applied mutation", async () => {
    const { adapter, layout } = await loadAdapter();
    const filePath = layout.nodes[0]?.filePath;
    if (filePath === undefined) throw new Error("sample has no functions");
    const original = readVirtual(adapter, filePath);

    const splice: SpliceRange = { filePath, startIndex: 0, endIndex: 0, replacement: "// edited\n", description: "edit" };
    await adapter.applyMutation({ splices: [splice] });
    expect(readVirtual(adapter, filePath)).toBe(`// edited\n${original}`);

    await adapter.reset();
    expect(readVirtual(adapter, filePath)).toBe(original);
  });
});
